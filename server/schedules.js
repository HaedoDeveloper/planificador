import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { once } from 'node:events';
import { SAXParser } from 'parse5-sax-parser';

export const SCHEDULE_SOURCE = 'https://horarios.frh.utn.edu.ar/';
export const MAX_SCHEDULE_BYTES = 16 * 1024 * 1024;
const normalize = s => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .replace(/\s*\((int|elec|elect|electiva)\.?\)\s*/gi, ' ').replace(/\s+/g, ' ').trim().toLowerCase();
const clean = (s, max = 140) => String(s ?? '').replace(/[\x00-\x1f\x7f]/g, '').replace(/\s+/g, ' ').trim().slice(0, max);
const days = {lunes: 1, martes: 2, miercoles: 3, jueves: 4, viernes: 5, sabado: 6};
const basics = new Set(['analisis matematico i', 'fisica i', 'quimica general', 'algebra y geometria analitica']);
function minutes(value) {
  const match = /^(\d{1,2}):(\d{2})$/.exec(clean(value));
  return match && +match[1] < 24 && +match[2] < 60 ? +match[1] * 60 + +match[2] : null;
}

export async function loadAcademicData() {
  const html = await readFile(new URL('../index.html', import.meta.url), 'utf8');
  // These declarations are JSON generated by the original build, not executable input.
  const careers = JSON.parse(/^const CARRERAS = (.+);\r?$/m.exec(html)[1]);
  const cycle = JSON.parse(/^(?:const|let) CICLO = (.+);\r?$/m.exec(html)[1]);
  return {careers, cycle};
}

export async function parseScheduleHTML(html, careers) {
  if (Buffer.byteLength(html) > MAX_SCHEDULE_BYTES) throw new Error('schedule_size_limit');
  const parser = new SAXParser();
  const rows = [];
  let cycleText = '', inCycle = false, closedHTML = false;
  parser.on('startTag', ({tagName, attrs}) => {
    const at = Object.fromEntries(attrs.map(({name, value}) => [name, value]));
    if (at.id === 'page-hero-sub') inCycle = true;
    if (tagName !== 'div' || !(at.class || '').split(/\s+/).includes('materia-bloque')) return;
    const c = JSON.parse(at['data-comision']);
    if (!c || typeof c !== 'object' || Array.isArray(c)) throw new Error('schedule_invalid_row');
    const dia = days[normalize(clean(c['Día'] || c.Dia))];
    const inicio = minutes(c['H. Comienzo']), fin = minutes(c['H. Fin']);
    const curso = clean(c.Curso, 40), materia = clean(c['Nombre Materia']);
    if (!dia || inicio === null || fin === null || inicio >= fin || !curso || !materia) throw new Error('schedule_invalid_time');
    const docentes = ['Titular', 'Adjunto', 'Asociado', 'Jtp', 'Ayudante 1ra', 'Ayudante 2da'].map(k => clean(c[k])).filter(Boolean);
    rows.push({carrera: clean(at['data-carrera-nombre']), curso, materia, plan: clean(c.Plan, 10),
      dictado: clean(c['Tipo Dictado'], 4), modalidad: at['data-modalidad'] === 'virtual' ? 'virtual' : 'presencial',
      docentes, bloque: {dia, inicio, fin, aula: clean(c.Aula, 60)}});
    if (rows.length > 30_000) throw new Error('schedule_row_limit');
  });
  parser.on('text', ({text}) => { if (inCycle) cycleText += text.slice(0, 100); });
  parser.on('endTag', ({tagName}) => { if (tagName === 'p') inCycle = false; if (tagName === 'html') closedHTML = true; });
  parser.resume();
  const finished = once(parser, 'finish');
  parser.end(html);
  await finished;
  const cycle = /Ciclo lectivo\s+(20\d{2})/i.exec(cycleText)?.[1];
  if (!cycle || !closedHTML || !rows.length) throw new Error('schedule_invalid_document');
  const output = {};
  for (const [slug, career] of Object.entries(careers)) {
    const rules = career.carrera.horarios;
    const english = new RegExp(rules.regexIngles);
    const selected = rows.filter(b => normalize(b.carrera) === normalize(rules.carrera) || english.test(b.curso) ||
      (basics.has(normalize(b.materia)) && /^[A-Z]{1,2}(-R)?$/.test(b.curso)));
    const current = new Set(selected.filter(b => b.plan === rules.planActual).map(b => normalize(b.materia)));
    const withoutR = new Set([...current, ...selected.filter(b => rules.planesViejos.includes(b.plan) && !b.curso.endsWith('-R')).map(b => normalize(b.materia))]);
    const groups = new Map();
    for (const b of selected) {
      const old = rules.planesViejos.includes(b.plan);
      if (b.plan !== rules.planActual && !(old && !current.has(normalize(b.materia)) &&
          (!b.curso.endsWith('-R') || !withoutR.has(normalize(b.materia))))) continue;
      if (!['A', '1', '2'].includes(b.dictado)) throw new Error('schedule_invalid_dictation');
      const key = b.curso + '|' + normalize(b.materia);
      if (!groups.has(key)) groups.set(key, {curso: b.curso, materia: b.materia, plan: b.plan, dictado: b.dictado,
        compartida: old, modalidad: b.modalidad, docentes: [], bloques: []});
      const group = groups.get(key);
      if (group.plan !== b.plan || group.dictado !== b.dictado) throw new Error('schedule_conflicting_rows');
      if (group.modalidad !== b.modalidad) group.modalidad = 'mixta';
      for (const teacher of b.docentes) if (!group.docentes.includes(teacher)) group.docentes.push(teacher);
      if (!group.bloques.some(x => x.dia === b.bloque.dia && x.inicio === b.bloque.inicio && x.fin === b.bloque.fin && x.aula === b.bloque.aula)) group.bloques.push(b.bloque);
    }
    output[slug] = [...groups.values()].sort((a, b) => (a.curso + '|' + a.materia).localeCompare(b.curso + '|' + b.materia, 'es'));
    for (const group of output[slug]) {
      group.docentes.sort();
      group.bloques.sort((a, b) => a.dia - b.dia || a.inicio - b.inicio || a.fin - b.fin || a.aula.localeCompare(b.aula));
    }
  }
  return {cycle, careers: output};
}

async function download(fetchImpl, signal) {
  const response = await fetchImpl(SCHEDULE_SOURCE, {redirect: 'error', signal,
    headers: {Accept: 'text/html', 'User-Agent': 'Planificador-UTN-FRH/1.0 (schedule synchronization)'}});
  if (!response.ok || !response.headers.get('content-type')?.includes('text/html') || !response.body) {
    await response.body?.cancel(); throw new Error('schedule_source_unavailable');
  }
  if (Number(response.headers.get('content-length')) > MAX_SCHEDULE_BYTES) {
    await response.body.cancel(); throw new Error('schedule_size_limit');
  }
  let size = 0;
  const chunks = [];
  for await (const chunk of response.body) {
    size += chunk.byteLength;
    if (size > MAX_SCHEDULE_BYTES) throw new Error('schedule_size_limit');
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString('utf8');
}

export async function createSchedules({store, now = Date.now, fetchImpl = fetch, intervalMs = 6 * 60 * 60_000,
  audit = event => console.log(JSON.stringify(event)), academic}) {
  const {careers, cycle} = academic || await loadAcademicData();
  let catalog = await store.getSchedules() || {cycle, source: SCHEDULE_SOURCE, kind: 'bundled', checkedAt: null, updatedAt: null,
    hash: 'bundled-' + cycle, careers: Object.fromEntries(Object.entries(careers).map(([slug, c]) => [slug, c.comisiones.comisiones]))};
  let pending = null, timer = null, controller = null, stopped = false;
  async function update() {
    controller = new AbortController();
    try {
      const html = await download(fetchImpl, AbortSignal.any([controller.signal, AbortSignal.timeout(30_000)]));
      const parsed = await parseScheduleHTML(html, careers);
      if (+parsed.cycle < +catalog.cycle) throw new Error('schedule_cycle_regression');
      for (const slug of Object.keys(careers)) {
        const count = parsed.careers[slug].length;
        const minimum = Math.max(1, Math.ceil(catalog.careers[slug].length * 0.6));
        if (count < minimum) throw new Error('schedule_incomplete_catalog');
      }
      const hash = createHash('sha256').update(JSON.stringify(parsed)).digest('hex');
      const stamp = new Date(now()).toISOString();
      const next = {...parsed, source: SCHEDULE_SOURCE, kind: 'official', hash, checkedAt: stamp,
        updatedAt: hash === catalog.hash ? catalog.updatedAt : stamp};
      await store.putSchedules(next);
      catalog = next;
      audit({event: 'schedules_updated', cycle: next.cycle, counts: Object.fromEntries(Object.entries(next.careers).map(([slug, rows]) => [slug, rows.length]))});
    } catch (error) {
      audit({event: 'schedules_update_failed', reason: /^schedule_[a-z_]+$/.test(error.message) ? error.message : 'source_or_storage_error'});
      throw error;
    } finally { controller = null; }
  }
  const service = {
    get(career) {
      const {careers: data, ...metadata} = catalog;
      return {...metadata, stale: !catalog.checkedAt || now() - Date.parse(catalog.checkedAt) > intervalMs * 2, comisiones: data[career]};
    },
    refresh() {
      if (stopped) return Promise.reject(new Error('schedule_stopped'));
      if (!pending) pending = update().finally(() => { pending = null; });
      return pending;
    },
    start() {
      if (timer || stopped) return;
      service.refresh().catch(() => {});
      timer = setInterval(() => service.refresh().catch(() => {}), intervalMs);
      timer.unref();
    },
    async stop() {
      stopped = true; clearInterval(timer); controller?.abort();
      await pending?.catch(() => {});
    },
  };
  return service;
}
